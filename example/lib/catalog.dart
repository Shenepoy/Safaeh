/// Catalog has no camera plugin. Web and desktop have no lens; phone builds
/// of this example also get the mock so chrome stays demoable.
bool catalogNeedsMockCamera() {
  if (kIsWeb) return true;
  return switch (defaultTargetPlatform) {
    TargetPlatform.macOS ||
    TargetPlatform.windows ||
    TargetPlatform.linux ||
    TargetPlatform.fuchsia ||
    TargetPlatform.android ||
    TargetPlatform.iOS => true,
  };
}

Locale catalogFlutterLocale(String code) {
  for (final item in catalogLocales) {
    if (item.code == code) return item.locale;
  }
  return const Locale('en');
}

/// Keep emails and similar tokens LTR inside RTL chrome.
Widget catalogIsolateLabel(String data, TextStyle? style) {
  final text = Text(
    data,
    style: style,
    maxLines: 1,
    overflow: TextOverflow.ellipsis,
  );
  if (data.contains('@')) {
    return Directionality(textDirection: TextDirection.ltr, child: text);
  }
  return text;
}

