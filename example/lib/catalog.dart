String translateCatalog(String key, String locale) {
  final table = catalogTranslations[locale];
  assert(
    table != null && table.containsKey(key),
    'Missing catalog key "$key" for locale "$locale"',
  );
  return table?[key] ?? catalogTranslations['en']?[key] ?? key;
}

/// Lays out catalog copy so CJK / Arabic glyphs exist before the page reveals.
Future<void> warmupCatalogLocale(String locale, {TextStyle? style}) async {
  final texts = catalogTranslations[locale];
  if (texts == null || texts.isEmpty) return;
  final painter = TextPainter(
    textDirection: locale == 'ar' ? TextDirection.rtl : TextDirection.ltr,
  );
  final resolved = style ?? const TextStyle(fontSize: 16, height: 1.3);
  for (final value in texts.values) {
    if (value.isEmpty) continue;
    painter.text = TextSpan(text: value, style: resolved);
    painter.layout(maxWidth: 480);
  }
  painter.dispose();
}
